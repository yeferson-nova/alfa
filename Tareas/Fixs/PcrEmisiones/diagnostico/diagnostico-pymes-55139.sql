-- Pymes (producto 55139) no llega a la extracción de movimientos de Generales en QA
-- (lote 20261122234023): 0 movimientos en Bronce, aunque la Oracle tiene 45 operaciones
-- de junio con estado 2 (Q4 de conciliacion-oracle-acsele.sql).
--
-- La consulta de movimientos de la extracción exige, para cada operación, que existan
-- POLICYDCO, AGREGATEDPOLICY, PREPRODUCT (compañía 'Seguros Alfa S.A.'), PREPOLICY,
-- EVENTDCO (misma operación y mismo evento) y RISKUNITDCO, y que el movimiento tenga
-- OPERATIONPK = operación y POLICYID = póliza.
-- Esta consulta cuenta cuántas operaciones de Pymes sobreviven a cada paso.
-- El primer paso donde el conteo cae a 0 es el que excluye a Pymes.
-- Solo lectura; no devuelve datos de personas.

WITH OPS AS (
  SELECT C.ID AS OPERATIONPK, P.DCOID, P.IDDCOEVENT, P.AGREGATEDOBJECTID AS POLICY_ID
  FROM ACSELE_ALFA.CONTEXTOPERATION C
  JOIN ACSELE_ALFA.POLICYDCO P        ON P.OPERATIONPK = C.ID
  JOIN ACSELE_ALFA.AGREGATEDPOLICY AP ON AP.AGREGATEDPOLICYID = P.AGREGATEDOBJECTID
  WHERE C.STATUS = 2
    AND C.TIME_STAMP >= TO_DATE('2026-06-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')
    AND C.TIME_STAMP <  TO_DATE('2026-07-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')
    AND AP.PRODUCTID = 55139
)
SELECT '1 operaciones de junio (estado 2)' AS PASO, COUNT(DISTINCT OPERATIONPK) AS OPERACIONES FROM OPS
UNION ALL
SELECT '2 + PREPRODUCT Seguros Alfa S.A.', COUNT(DISTINCT O.OPERATIONPK)
FROM OPS O
WHERE EXISTS (SELECT 1 FROM ACSELE_ALFA.PREPRODUCT PP WHERE PP.STATIC = 55139 AND PP.COMPANIAINPUT = 'Seguros Alfa S.A.')
UNION ALL
SELECT '3 + PREPOLICY', COUNT(DISTINCT O.OPERATIONPK)
FROM OPS O JOIN ACSELE_ALFA.PREPOLICY PPL ON PPL.PK = O.DCOID
UNION ALL
SELECT '4 + EVENTDCO (operacion y evento)', COUNT(DISTINCT O.OPERATIONPK)
FROM OPS O
JOIN ACSELE_ALFA.PREPOLICY PPL ON PPL.PK = O.DCOID
JOIN ACSELE_ALFA.EVENTDCO E    ON E.OPERATIONPK = O.OPERATIONPK AND E.IDDCOEVENT = O.IDDCOEVENT
UNION ALL
SELECT '5 + RISKUNITDCO', COUNT(DISTINCT O.OPERATIONPK)
FROM OPS O
JOIN ACSELE_ALFA.PREPOLICY PPL ON PPL.PK = O.DCOID
JOIN ACSELE_ALFA.EVENTDCO E    ON E.OPERATIONPK = O.OPERATIONPK AND E.IDDCOEVENT = O.IDDCOEVENT
JOIN ACSELE_ALFA.RISKUNITDCO R ON R.OPERATIONPK = O.OPERATIONPK
UNION ALL
SELECT '6 movimientos por OPERATIONPK (sin exigir POLICYID)', COUNT(DISTINCT T.OPERATIONPK)
FROM OPS O JOIN ACSELE_ALFA.THIRDPARTYMOVEMENTPOLICY T ON T.OPERATIONPK = O.OPERATIONPK AND T.AMMOUNT <> 0
UNION ALL
SELECT '7 movimientos por OPERATIONPK y POLICYID', COUNT(DISTINCT T.OPERATIONPK)
FROM OPS O JOIN ACSELE_ALFA.THIRDPARTYMOVEMENTPOLICY T
  ON T.OPERATIONPK = O.OPERATIONPK AND T.POLICYID = O.POLICY_ID AND T.AMMOUNT <> 0;

-- Si el paso 6 tiene operaciones y el 7 no, los movimientos de Pymes se registran con
-- otra póliza (por ejemplo la del acuerdo) y la llave OPERATIONPK + POLICYID no aplica.
-- En ese caso, este bloque muestra la forma de la llave (solo conteos):
SELECT CASE WHEN T.POLICYID = O.POLICY_ID THEN 'POLICYID = poliza de la operacion'
            ELSE 'POLICYID distinto' END AS LLAVE,
       COUNT(*) AS MOVIMIENTOS, SUM(T.AMMOUNT) AS TOTAL
FROM (SELECT C.ID AS OPERATIONPK, P.AGREGATEDOBJECTID AS POLICY_ID
      FROM ACSELE_ALFA.CONTEXTOPERATION C
      JOIN ACSELE_ALFA.POLICYDCO P        ON P.OPERATIONPK = C.ID
      JOIN ACSELE_ALFA.AGREGATEDPOLICY AP ON AP.AGREGATEDPOLICYID = P.AGREGATEDOBJECTID
      WHERE C.STATUS = 2
        AND C.TIME_STAMP >= TO_DATE('2026-06-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')
        AND C.TIME_STAMP <  TO_DATE('2026-07-01 00:00:00', 'YYYY-MM-DD HH24:MI:SS')
        AND AP.PRODUCTID = 55139) O
JOIN ACSELE_ALFA.THIRDPARTYMOVEMENTPOLICY T ON T.OPERATIONPK = O.OPERATIONPK AND T.AMMOUNT <> 0
GROUP BY CASE WHEN T.POLICYID = O.POLICY_ID THEN 'POLICYID = poliza de la operacion' ELSE 'POLICYID distinto' END;
